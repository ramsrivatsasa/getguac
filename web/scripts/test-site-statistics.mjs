import assert from 'node:assert/strict'
import {calendarDay,cleanStatisticsPath,statisticsDimensions,dayBoundary,summarizeStatistics,CLIENT_EVENTS} from '../src/lib/site-statistics.mjs'
assert.equal(calendarDay(new Date('2026-10-15T01:00Z'),'America/New_York'),'2026-10-14')
assert.equal(calendarDay(new Date('2026-10-15T01:00Z'),'UTC'),'2026-10-15')
assert.equal(cleanStatisticsPath('/register?email=private@example.test'),'/register')
assert.equal(cleanStatisticsPath('/admin/crashes'),null)
assert.equal(cleanStatisticsPath('//outside.test'),null)
assert.equal(cleanStatisticsPath('/person/private%40example.test'),null)
assert.equal(cleanStatisticsPath('/receipts/12345678-1234-1234-1234-123456789012'),'/receipts/[record]')
assert.equal(CLIENT_EVENTS.has('account_created'),false)
assert.equal(dayBoundary('2026-03-08','America/New_York'),'2026-03-08T05:00:00.000Z')
assert.equal(dayBoundary('2026-03-09','America/New_York'),'2026-03-09T04:00:00.000Z')
assert.equal(dayBoundary('2026-11-01','America/New_York'),'2026-11-01T04:00:00.000Z')
assert.equal(dayBoundary('2026-11-02','America/New_York'),'2026-11-02T05:00:00.000Z')
const geo=statisticsDimensions(new Headers({'x-vercel-ip-city':'New%20York','x-vercel-ip-country':'US','x-vercel-ip-country-region':'NY','user-agent':'Mobile Safari'}),'https://www.instagram.com/example?private=value')
assert.deepEqual(geo,{country:'US',region:'NY',city:'New York',device:'Mobile',source:'Social'})
assert.equal(statisticsDimensions(new Headers()).city,'Unknown')
const row=(id,time,path,event='page_view',visitor='a')=>({id,occurred_at:`2026-10-14T${time}:00Z`,visitor_hash:visitor,path,event,...geo})
const result=summarizeStatistics([
 row(1,'10:00','/join'),row(2,'10:01','/register'),row(3,'10:02','/register','signup_start'),row(4,'10:03','/register','signup_submit'),row(5,'10:04','/register','account_created'),row(6,'10:05','/register','email_confirmed'),
 row(7,'11:00','/login'),row(8,'11:01','/join','signup_error','b'),row(9,'12:55','/faq','page_view','c'),row(10,'09:00','/join','page_view',null)
],{timezone:'UTC',now:Date.parse('2026-10-14T13:00:00Z')})
assert.equal(result.views,5)
assert.equal(result.visitorDays,3)
assert.deepEqual(result.funnel,{visits:3,registration:1,started:1,submitted:1,created:1,confirmed:1})
assert.equal(result.closedSessions,2)
assert.equal(result.openSessions,1)
assert.equal(result.lastPages.find(p=>p.name==='/login').count,1)
assert.equal(result.lastPages.some(p=>p.name==='/faq'),false)
assert.equal(result.eventTotals.account_created,1)
assert.equal(result.eventTotals.signup_error,1)
assert.equal(result.transitions[0].name,'/join → /register')
assert.equal(result.locations[0].count,5)
// Out-of-order delivery is sorted; a created event without preceding signup steps
// must never manufacture a conversion in the ordered funnel.
const orphan=summarizeStatistics([row(2,'10:04','/register','account_created'),row(1,'10:00','/join')],{now:Date.parse('2026-10-14T13:00Z')})
assert.equal(orphan.funnel.created,0)
assert.equal(orphan.eventTotals.account_created,1)
